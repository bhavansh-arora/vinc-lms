// Builds assets/js/i18n/hi/data.js: English → Hindi for project, activity and lab titles, taken
// from the English and Hindi course and lesson files. Saved activity-feed lines (stored in English)
// use these to show the titles in Hindi. Run again after changing course or lesson titles:
//   node scripts/make-hindi-titles.mjs
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const load = p => import(resolve(ROOT, p));
const out = {};
const add = (e, h) => { if (typeof e === 'string' && typeof h === 'string' && e && h && e !== h) out[e] = h; };
for (const g of [6, 7, 8]) {
  const E = (await load(`assets/js/data/grade${g}.js`))[`GRADE${g}`], H = (await load(`assets/js/data/hi/grade${g}.js`))[`GRADE${g}`];
  E.projects.forEach((p, i) => {
    const q = H.projects[i];
    add(p.title, q.title);
    (p.activities || []).forEach((a, j) => add(a.title, q.activities?.[j]?.title));
  });
  for (let n = 1; n <= 6; n++) {
    const pid = `g${g}p${n}`;
    const LE = (await load(`assets/js/data/lessons/${pid}.js`)).LESSONS, LH = (await load(`assets/js/data/lessons/hi/${pid}.js`)).LESSONS;
    for (const k of Object.keys(LE)) add(LE[k].lab?.title, LH[k]?.lab?.title);
  }
}
const body = Object.entries(out).sort().map(([e, h]) => `  ${JSON.stringify(e)}: ${JSON.stringify(h)},`).join('\n');
writeFileSync(resolve(ROOT, 'assets/js/i18n/hi/data.js'), `// Generated by scripts/make-hindi-titles.mjs from the course and lesson files. Do not edit by hand.\nexport const patterns = [];\nexport default {\n${body}\n};\n`);
console.log(`${Object.keys(out).length} titles`);
